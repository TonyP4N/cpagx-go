#!/usr/bin/env python3
"""Formal R18 task/restore harness extended with independent R19 evaluation.

All annotations below are handwritten fixture expectations, before any analysis.
Uses generated bytes only; this is not reference-environment capacity acceptance.
"""
import argparse
from datetime import datetime,timedelta,timezone
import json
import os
import secrets
from pathlib import Path
import sys
import time
ROOT=Path(__file__).resolve().parents[2]
sys.path[:0]=[str(ROOT/'services/analysis/src'),str(ROOT/'services/worker'),str(ROOT/'scripts/backup')]
import round18_acceptance as r18
from cpag_core import evaluation_bundle as eb
from cpag_core.evaluation import digest

EXPECTED=[('manual-operation','network_operation','["192.0.2.2",44818]','2026-01-01T00:00:10Z'),
          ('manual-transition','process_change','["synthetic-pump","pump_state"]','2026-01-01T00:00:12Z')]

def run(work):
    original=r18.check_run;records={};checks=[];offline={};offline_checked=set();role_checks=[]
    def checked(client,job,root,attempt,config,case):
        result=original(client,job,root,attempt,config,case) if case!='offline' else {}
        if case not in ('normal','offline'):return result
        artifact=root/'jobs'/job/f'attempt-{attempt}'
        projection=client.expect('GET',f'/api/v3/runs/{job}/evaluation-input?projection=dual')
        assert len(projection['predictions']['events'])==2
        assert len(projection['predictions']['unlabelled_relations'])==1
        if job not in records:
            b=projection['binding'];sample=b['sample_sha256'];batch=b['batch']
            split={'schema_version':'1.0.0','synthetic':True,'rule_windows_seconds':{'association':5},'isolation_seconds':5,'blocks':[
              {'partition':'calibration','batch':batch,'start':'2025-12-01T00:00:00Z','end':'2025-12-01T00:01:00Z','sample_sha256':['a'*64],'normal':False},
              {'partition':'holdout','batch':batch,'start':'2026-01-01T00:00:00Z','end':'2026-01-01T00:01:00Z','sample_sha256':[sample],'normal':False}]}
            now=datetime.now(timezone.utc);opening=now+timedelta(seconds=5)
            reg={'schema_version':'1.0.0','synthetic':True,'registered_at':now.isoformat(),'holdout_opened_at':opening.isoformat(),
                 'input_fingerprint':b['input_fingerprint'],'config_fingerprint':b['config_fingerprint'],'split_sha256':digest(split),'tolerance_seconds':0,'thresholds':{}}
            frozen=work/('frozen-'+job);out=work/('evaluation-'+job)
            eb.freeze(artifact,split,reg,frozen,batch=batch,sample_sha256=sample)
            labels={'schema_version':'1.0.0','synthetic':True,'origin':'independent','source_ref':'round19 handwritten expected table','review_ref':'repository test author','annotation_version':'1',
                    'events':[{'id':i,'kind':kind,'asset':asset,'time':at,'batch':batch,'sample_sha256':sample} for i,kind,asset,at in EXPECTED],'disputed_intervals':[]}
            # Mutate only independent labels before evaluating the second fresh run.
            # Its analysis has already used the same allowlisted originals/config.
            changed=case=='normal' and sum(v['mode']=='replay' for v in records.values())==1
            if changed:labels['events'][1]['time']='2026-01-01T00:00:14Z'
            (work/'independent-labels.json').write_text(json.dumps(labels))
            refs={e['id']:{'source_ref':'scripts/validation/round19_evaluation_acceptance.py EXPECTED','record':e['id'],'sha256':digest(EXPECTED)} for e in labels['events']}
            time.sleep(max(0,(opening-datetime.now(timezone.utc)).total_seconds())+.01)
            measured=eb.evaluate_bundle(frozen,artifact,labels,refs,out)
            expected=(1,1,1) if changed else (2,0,0)
            assert tuple(measured['record']['metrics'][k] for k in ('tp','fp','fn'))==expected
            document={p.name:eb.read(p) for p in out.iterdir()}
            imported=client.expect('POST',f'/api/v3/runs/{job}/evaluations',document,code=201)
            records[job]={'id':imported['evaluation']['id'],'document':document,'expected':expected,'label_changed':changed,'mode':'offline' if case=='offline' else 'replay'}
        entry=records[job]
        response=client.expect('GET',f"/api/v3/runs/{job}/evaluations/{entry['id']}")
        assert response['evaluation']['document_sha256']==digest(entry['document'])
        pid=projection['predictions']['events'][0]['id']
        from urllib.parse import urlencode
        evidence=client.expect('GET',f"/api/v3/runs/{job}/evaluations/{entry['id']}/evidence?"+urlencode({'event':pid}))
        checks.append({'job':job,'attempt':attempt,'stage':'restored' if 'restored' in str(root) else 'original','expected_tp_fp_fn':entry['expected'],'label_changed':entry['label_changed'],'mode':entry['mode'],'evaluation_id':entry['id'],'evidence_available':bool(evidence)})
        if case=='normal' and not role_checks:
            meta=client.expect('GET',f'/api/v3/runs/{job}')['run']
            username='r19-viewer';password=secrets.token_urlsafe(24)
            uid=client.expect('POST','/api/v3/users',{'username':username,'password':password,'role':'viewer'},code=201)['user']['id']
            viewer=r18.r.Client(client.origin);viewer.expect('POST','/api/v3/session',{'username':username,'password':password})
            viewer.expect('GET',f"/api/v3/runs/{job}/evaluations/{entry['id']}",code=404)
            client.expect('POST',f"/api/v3/datasets/{meta['dataset_id']}/acl",{'user_id':uid,'access':'viewer'})
            viewer.expect('GET',f"/api/v3/runs/{job}/evaluations/{entry['id']}")
            viewer.expect('POST',f'/api/v3/runs/{job}/evaluations',entry['document'],code=403)
            duplicate=client.expect('POST',f'/api/v3/runs/{job}/evaluations',entry['document'])
            assert duplicate['evaluation']['id']==entry['id']
            role_checks.append({'ungranted_read':404,'granted_read':200,'viewer_write':403,'duplicate_same_id':True})
            submitted=client.expect('POST','/api/v3/runs',{'dataset_id':meta['dataset_id'],'config_version_id':meta['config_version_id'],'preflight_id':meta['preflight_id'],'mode':'dual_source'},code=201)['run']['id']
            status=r18.r.status_until(client,submitted);assert status['state']=='succeeded',status
            offline.update(job=submitted,attempt=status['attempt'])
        if case=='normal' and offline and str(root) not in offline_checked:
            offline_checked.add(str(root))
            checked(client,offline['job'],root,offline['attempt'],config,'offline')
        return result
    r18.check_run=checked
    try:r18.main(work)
    finally:
        if (work/'public').exists():(work/'public/round19-evaluation.json').write_text(json.dumps({'checks':checks,'roles':role_checks,'scope':'formal synthetic task plus terminal PG/file restore; not capacity or industrial validation'},indent=2))
        r18.check_run=original

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--output',required=True);a=p.parse_args();run(Path(a.output).resolve())
